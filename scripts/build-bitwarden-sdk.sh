#!/usr/bin/env bash
# Builds Bitwarden's Rust SDK (sdk-internal) as a macOS xcframework plus its
# generated Swift bindings, into Vendor/BitwardenSdk. Bitwarden only publishes
# an iOS build of the Swift package, so the macOS one is built locally.
set -euo pipefail

SDK_REV="${SDK_REV:-8ed0081a8a215a6507f92b31f0f2c31a9ca51a33}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/.local/sdk-internal"
OUT="$ROOT/Vendor/BitwardenSdk"

mkdir -p "$ROOT/.local"
if [[ ! -d "$SRC/.git" ]]; then
  git clone --filter=blob:none https://github.com/bitwarden/sdk-internal.git "$SRC"
fi
git -C "$SRC" fetch --quiet origin "$SDK_REV"
git -C "$SRC" checkout --quiet --detach "$SDK_REV"

export MACOSX_DEPLOYMENT_TARGET=15.0
# Fails the build if a commercially licensed crate leaks in, keeping the result GPL-only.
export RUSTFLAGS="--cfg bitwarden_ensure_non_commercial"

cd "$SRC"
cargo build --package bitwarden-uniffi --target aarch64-apple-darwin --release
LIB_DIR="$SRC/target/aarch64-apple-darwin/release"

TMP="$(mktemp -d "$ROOT/.local/sdk-build.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

cargo run --quiet --package uniffi-bindgen generate \
  "$LIB_DIR/libbitwarden_uniffi.dylib" \
  --language swift \
  --no-format \
  --out-dir "$TMP/bindings"

rm -rf "$OUT"
mkdir -p "$OUT/Sources/BitwardenSdk" "$TMP/Headers"
cp -R "$SRC/crates/bitwarden-uniffi/swift/Sources/BitwardenSdkSupport" "$OUT/Sources/"
mv "$TMP"/bindings/*.swift "$OUT/Sources/BitwardenSdk/"
mv "$TMP"/bindings/*.h "$TMP/Headers/"
cat "$TMP"/bindings/*.modulemap > "$TMP/Headers/module.modulemap"

xcodebuild -create-xcframework \
  -library "$LIB_DIR/libbitwarden_uniffi.a" \
  -headers "$TMP/Headers" \
  -output "$OUT/BitwardenFFI.xcframework"

cp "$SRC/crates/bitwarden-uniffi/swift/LICENSE_GPL.txt" "$OUT/"
echo "$SDK_REV" > "$OUT/REVISION"

cat > "$OUT/Package.swift" <<'SWIFT'
// swift-tools-version: 6.0
// Generated by scripts/build-bitwarden-sdk.sh. Do not edit.
import PackageDescription

let package = Package(
    name: "BitwardenSdk",
    platforms: [.macOS(.v15)],
    products: [
        .library(name: "BitwardenSdk", targets: ["BitwardenSdk"]),
    ],
    targets: [
        .target(
            name: "BitwardenSdk",
            dependencies: ["BitwardenFFI", "BitwardenSdkSupport"],
            swiftSettings: [.unsafeFlags(["-suppress-warnings"])]
        ),
        .target(name: "BitwardenSdkSupport"),
        .binaryTarget(name: "BitwardenFFI", path: "BitwardenFFI.xcframework"),
    ],
    // The generated bindings predate Swift 6 strict concurrency.
    swiftLanguageModes: [.v5]
)
SWIFT

echo "Bitwarden SDK $SDK_REV built into $OUT"
